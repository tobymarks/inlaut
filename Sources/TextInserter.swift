import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Clipboard-backed insertion, bound to the app/field where dictation began.
@MainActor
enum TextInserter {
    struct Target {
        let processID: pid_t
        let element: AXUIElement?
    }

    enum Result: Equatable {
        case inserted
        case copied(String)
    }

    /// Injected in tests so no real clipboard, keyboard or focused app is touched.
    struct Environment {
        var isTrusted: () -> Bool
        var targetUnchanged: () -> Bool
        var waitForModifiers: () async throws -> Bool
        var postPaste: () -> Bool
        var waitForPaste: () async throws -> Void
    }

    static var isTrusted: Bool { AXIsProcessTrusted() }

    static func requestTrust() {
        AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt" as CFString: true] as CFDictionary)
    }

    static func captureTarget() -> Target? {
        guard let app = NSWorkspace.shared.frontmostApplication else { return nil }
        return Target(processID: app.processIdentifier, element: isTrusted ? focusedElement() : nil)
    }

    static func insert(_ text: String, target: Target?) async throws -> Result {
        try await insert(text, pasteboard: .general, environment: Environment(
            isTrusted: { isTrusted },
            targetUnchanged: { matches(target) },
            waitForModifiers: waitForModifiersReleased,
            postPaste: postCommandV,
            waitForPaste: { try await Task.sleep(for: .milliseconds(400)) }
        ))
    }

    static func insert(_ text: String, pasteboard: NSPasteboard, environment: Environment) async throws -> Result {
        try Task.checkCancellation()
        guard environment.isTrusted() else {
            copy(text, to: pasteboard)
            return .copied(String(localized: "On the clipboard – allow Accessibility to paste"))
        }
        // Wait before modifying the clipboard. Anything copied while the user
        // releases the hotkey is now included in the snapshot and preserved.
        let released = try await environment.waitForModifiers()
        try Task.checkCancellation()
        guard released else {
            copy(text, to: pasteboard)
            return .copied(String(localized: "On the clipboard – release the modifier keys and paste with ⌘V"))
        }
        guard environment.targetUnchanged() else {
            copy(text, to: pasteboard)
            return .copied(String(localized: "Text field changed – paste the dictation with ⌘V"))
        }

        // The clipboard of the dictation before may still hold our text.
        restoreNow()
        let saved = snapshot(pasteboard)
        copy(text, to: pasteboard)
        let ours = pasteboard.changeCount
        guard environment.postPaste() else {
            return .copied(String(localized: "On the clipboard – paste the dictation with ⌘V"))
        }

        // The old clipboard comes back once the target app has had time to
        // read ours, also an originally empty one. That wait runs on its own,
        // so the next dictation can start right after the paste (#43). A new
        // copy by the user always wins over our snapshot.
        restoreGeneration += 1
        let generation = restoreGeneration
        pendingRestore = (generation, {
            guard pasteboard.changeCount == ours else { return }
            pasteboard.clearContents()
            if !saved.isEmpty { pasteboard.writeObjects(saved) }
        })
        let wait = environment.waitForPaste
        restoring = Task {
            try? await wait()
            if pendingRestore?.generation == generation { restoreNow() }
        }
        return .inserted
    }

    /// The wait of the latest paste; tests await it.
    private(set) static var restoring: Task<Void, Never>?
    private static var restoreGeneration = 0
    private static var pendingRestore: (generation: Int, run: () -> Void)?

    /// Puts the user's clipboard back without waiting any longer.
    static func restoreNow() {
        guard let pending = pendingRestore else { return }
        pendingRestore = nil
        pending.run()
    }

    private static func copy(_ text: String, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
    }

    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { original in
            let copy = NSPasteboardItem()
            for type in original.types {
                if let data = original.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func matches(_ target: Target?) -> Bool {
        guard let target,
              NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processID else { return false }
        // Some apps expose no AX field; keep the existing paste support for
        // them, but still prevent insertion into a different application.
        guard let original = target.element else { return true }
        guard let current = focusedElement() else { return false }
        return CFEqual(original, current)
    }

    private static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.15)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }

    private static func waitForModifiersReleased() async throws -> Bool {
        let held: CGEventFlags = [.maskAlternate, .maskShift, .maskControl, .maskCommand]
        for _ in 0..<40 {
            if CGEventSource.flagsState(.combinedSessionState).intersection(held).isEmpty { return true }
            try await Task.sleep(for: .milliseconds(25))
        }
        return false
    }

    private static func postCommandV() -> Bool {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = pasteKeyCode()
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false) else { return false }
        for event in [down, up] {
            event.flags = .maskCommand
            event.post(tap: .cghidEventTap)
        }
        return true
    }

    /// Key codes are positions on the keyboard, not letters: where QWERTY
    /// has V, Dvorak has K, and ⌘K is not paste (#46).
    private static func pasteKeyCode() -> CGKeyCode {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let layout = layoutData(of: source),
              let code = keyCode(producing: "v", in: layout) else { return CGKeyCode(kVK_ANSI_V) }
        return code
    }

    static func layoutData(of source: TISInputSource) -> Data? {
        guard let pointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        return Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
    }

    /// The key that types `character` while ⌘ is held, which is how the
    /// target app reads the shortcut ("Dvorak – QWERTY ⌘" keeps V in place).
    static func keyCode(producing character: String, in layout: Data) -> CGKeyCode? {
        layout.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let keyboard = bytes.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return nil }
            let command = UInt32(cmdKey >> 8) & 0xFF
            for code in UInt16(0)..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var typed = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(keyboard, code, UInt16(kUCKeyActionDown), command, UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysMask), &deadKeys, typed.count, &length, &typed)
                if status == noErr, length == 1, String(utf16CodeUnits: typed, count: 1).lowercased() == character {
                    return code
                }
            }
            return nil
        }
    }
}
